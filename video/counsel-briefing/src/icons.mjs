for (const [name, rows] of Object.entries(RAW)) {
  if (rows.length !== GRID) throw new Error(`icon ${name}: ${rows.length} rows, expected ${GRID}`);
  rows.forEach((row, i) => {
    if (row.length !== GRID) throw new Error(`icon ${name}: row ${i} is ${row.length} wide, expected ${GRID}`);
    if (/[^.#+]/.test(row)) throw new Error(`icon ${name}: row ${i} has a character outside . # +`);
  });
}

/** Horizontal runs of one character, merged into a single SVG path. */
function pathFor(rows, char) {
  let d = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== char) {
        x += 1;
        continue;
      }
      let end = x;
      while (end < row.length && row[end] === char) end += 1;
      d += `M${x} ${y}h${end - x}v1h-${end - x}z`;
      x = end;
    }
  });
  return d;
}

export const iconNames = Object.keys(RAW);

/**
 * An inline SVG. `color` paints '#', `accent` paints '+'. Rendered with crisp
 * edges so scaling up keeps the stair-steps the original artwork has.
 */
export function icon(name, { px = 96, color = 'currentColor', accent = 'var(--lilac)', cls = '' } = {}) {
  const rows = RAW[name];
  if (!rows) throw new Error(`unknown icon: ${name}`);
  const main = pathFor(rows, '#');
  const second = pathFor(rows, '+');
  return (
    `<svg class="ico ${cls}" viewBox="0 0 ${GRID} ${GRID}" ` +
    `width="${px}" height="${px}" shape-rendering="crispEdges" aria-hidden="true">` +
    (main ? `<path d="${main}" fill="${color}"/>` : '') +
    (second ? `<path d="${second}" fill="${accent}"/>` : '') +
    `</svg>`
  );
}
